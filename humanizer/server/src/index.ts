app.post('/api/humanize-code', async (req, res) => {
  const { code, language } = req.body;

  if (!code) {
    return res.status(400).json({ error: 'Code is required' });
  }

  try {
    const apiKey = process.env.GROK_API_KEY;
    if (!apiKey) {
      return res.json({
        humanizedCode: code,
        explanation: "API Key not configured. Returning original code.",
        isMock: true
      });
    }

    const response = await axios.post(
      'https://api.groq.com/openai/v1/chat/completions',
      {
        model: 'llama-3.3-70b-versatile',
        messages: [
          {
            role: 'system',
            content: `You are a senior software engineer. Your task is to refine AI-generated code to make it look like it was written by a human developer.
            
            Strict Guidelines:
            1. INDENTATION: Use exactly 2 spaces for indentation. Never use 4 spaces or tabs.
            2. BASELINE: Start the first line of code at column 0 (no leading whitespace). Only indent lines that are logically nested (e.g., inside functions, loops, or objects).
            3. COMMENTS: Do not be silent, but do not be verbose. Add a few "high-signal" comments only to explain tough or non-obvious lines of code. Avoid commenting standard boilerplate or self-explanatory logic.
            4. STYLE: Use clean, idiomatic patterns. Avoid overly "perfect" boilerplate.
            5. NAMING: Ensure variable names are descriptive but not overly long or clinical.
            
            Return your response in JSON format with two fields: "humanizedCode" (the updated code) and "explanation" (a brief note on what was cleaned up).`
          },
          {
            role: 'user',
            content: `Language: ${language || 'unknown'}\n\nCode:\n${code}`
          }
        ],
        response_format: { type: 'json_object' }
      },
      {
        headers: {
          'Authorization': `Bearer ${apiKey}`,
          'Content-Type': 'application/json'
        }
      }
    );

    const result = JSON.parse(response.data.choices[0].message.content);
    if (result.humanizedCode) {
      result.humanizedCode = result.humanizedCode.trim();
    }
    res.json(result);
  } catch (error: any) {
    console.error('Error calling Groq API:', error.response?.data || error.message);
    res.status(500).json({ error: 'Failed to humanize code' });
  }
});

