import express from 'express';
import cors from 'cors';
import dotenv from 'dotenv';
import axios from 'axios';

dotenv.config();

const app = express();
const port = process.env.PORT || 3001;

app.use(cors());
app.use(express.json());

app.post('/api/detect', async (req, res) => {
  const { text } = req.body;

  if (!text) {
    return res.status(400).json({ error: 'Text is required' });
  }

  try {
    const apiKey = process.env.GROK_API_KEY;
    if (!apiKey) {
      // Mock response if API key is missing for development
      return res.json({
        percentage: Math.floor(Math.random() * 100),
        reasoning: "API Key not configured. This is a mock response.",
        isMock: true
      });
    }

    const response = await axios.post(
      'https://api.groq.com/openai/v1/chat/completions',
      {
        model: 'llama-3.3-70b-versatile',
        messages: [
          {
            role: 'system',
            content: 'You are an AI text detector. Analyze the provided text and estimate the probability that it was generated by an AI. Return your response in JSON format with two fields: "percentage" (a number from 0 to 100) and "reasoning" (a brief explanation).'
          },
          {
            role: 'user',
            content: text
          }
        ],
        response_format: { type: 'json_object' }
      },
      {
        headers: {
          'Authorization': `Bearer ${apiKey}`,
          'Content-Type': 'application/json'
        }
      }
    );

    const result = JSON.parse(response.data.choices[0].message.content);
    res.json(result);
  } catch (error: any) {
    console.error('Error calling Grok API:', error.response?.data || error.message);
    res.status(500).json({ error: 'Failed to analyze text' });
  }
});

